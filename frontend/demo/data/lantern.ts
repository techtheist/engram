/**
 * The demo graph: the reasoning memory of **Lantern**, a fictional
 * local-first reading app, as an assistant would have captured it over a few
 * months of work.
 *
 * It is invented on purpose — shipping this repo's own graph would leak
 * working notes, and a stranger's project teaches nothing on sight. What is
 * NOT invented is the memory practice woven through it: the notes tagged
 * `memory-practice` state Engram's load-bearing rules (research-first,
 * models nominate and people judge, trust reads deliberate acts, retired
 * means retired, conflicts are surfaced and never auto-resolved). Those hold
 * across releases, so the demo can't go stale against the product.
 *
 * Ages are relative days, resolved against "now" at load — the demo is
 * always freshly plausible, never dated. Node ids are derived from the keys
 * (see `synthId`), so edges and canned payloads can reference notes by name.
 */
import type { Durability, NodeStatus, Source } from '@/types/graph'

export interface SeedNode {
    /** Stable authoring handle; hashed into the node's id. */
    key: string
    type: string
    title: string
    body?: string
    durability: Durability
    source: Source
    status?: NodeStatus
    /** Days before "now" the note was captured. */
    days: number
    /** Days before now of the last deliberate update ("still true"). */
    confirmed?: number
    /** Days before now the user approved it (trust restarts at 100%). */
    approved?: number
    /** Days before now contradicting evidence landed. */
    demoted?: number
    /** Constant-trust pin (user-only gesture). */
    pin?: number
    /** Days before now it was archived — superseded or decayed. */
    archived?: number
    tags?: string[]
    code_refs?: string[]
    version?: string
    session?: string
}

export interface SeedEdge {
    type: string
    from: string
    to: string
    source: Source
    days: number
    note?: string
    status?: string
}

